import numpy as np
from itertools import combinations
from cd import *
rng = np.random.default_rng(3)

def rand_im8():
    v = rng.standard_normal(8); v[0] = 0; return unit(v)
def pair(a, b): return np.concatenate([a, b])
def ok(label, cond): print(('PASS ' if cond else 'FAIL ') + label)

# ---------------------------------------------------------------- annihilator closed form
print('=== closed form of Ann(u + b l) in Sm ===')
good = True
for trial in range(30):
    u = rand_im8(); b = unit(rand(8, rng))
    x = pair(u, b)
    K = L('Sm', x); U, s, Vt = np.linalg.svd(K); k = nullity(K); ker = Vt[-k:].T
    # predicted: n in Im O, n ⊥ u, [b,n,u]=0 ; y = (n u, b n)
    # compute the space N = {n : n0=0, <n,u>=0, [b,n,u]=0}
    A = np.zeros((8 + 1 + 1, 8))
    for i in range(8):
        n = basis(8, i)
        A[:8, i] = assoc('O', b, n, u); A[8, i] = n[0]; A[9, i] = n @ u
    U2, s2, Vt2 = np.linalg.svd(A); kN = nullity(A); N = Vt2[-kN:].T
    Y = np.column_stack([pair(mulO(N[:, j], u), mulO(b, N[:, j])) for j in range(kN)])
    # same span?
    if not (kN == k and np.linalg.matrix_rank(np.hstack([ker, Y]), tol=1e-8) == k):
        good = False
    if not all(np.allclose(mul('Sm', x, Y[:, j]), 0, atol=1e-9) for j in range(kN)): good = False
ok('Ann(u+bl) = {nu + (bn)l : n ⊥ u imaginary, [b,n,u]=0} (30 random points)', good)
# special point
u = rand_im8(); b = np.cos(.3) * basis(8, 0) + np.sin(.3) * u
x = pair(u, b); print('  special point b in span{1,u}: ann dim', nullity(L('Sm', x)))

