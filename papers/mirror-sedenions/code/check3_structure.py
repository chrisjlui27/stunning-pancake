# ---------------------------------------------------------------- derivations
print('=== derivation algebra dimension ===')
def der_dim(name):
    T = struct(name); n = T.shape[0]
    # unknown D (n x n); equations D(e_i e_j) = D(e_i) e_j + e_i D(e_j)
    rows = []
    for i in range(n):
        for j in range(n):
            # coefficient matrix for vec(D): row index (i,j,k)
            eq = np.zeros((n, n, n))     # eq[k, p, q] coefficient of D[p,q] (D e_q = sum_p D[p,q] e_p)
            # D(e_i e_j)_k = sum_m T[i,j,m] D[k,m]
            for m in range(n):
                eq[:, :, m][np.arange(n), np.arange(n)] += T[i, j, m]
            # (D e_i) e_j = sum_p D[p,i] e_p e_j -> component k: sum_p D[p,i] T[p,j,k]
            for p in range(n):
                eq[:, p, i] -= T[p, j, :]
            # e_i (D e_j) = sum_p D[p,j] e_i e_p -> k: sum_p D[p,j] T[i,p,k]
            for p in range(n):
                eq[:, p, j] -= T[i, p, :]
            rows.append(eq.reshape(n, n * n))
    A = np.vstack(rows)
    return nullity(A)
for name in ['O', 'S', 'Sm', 'Om']:
    print(f'  Der({name}) has dimension {der_dim(name)}')
