# ---------------------------------------------------------------- pair manifold smoothness: rank of d(mu) on every stratum
print('=== rank of d(mu)(x,y) = [R_y | L_x] at points of P (expect 16 everywhere) ===')
ranks = set()
for trial in range(200):
    u = rand_im8(); n = rand_im8(); n = unit(n - (n @ u) * u)
    t = rng.random()
    if trial % 4 == 0:   # doubly special: b = ±u
        b = u * (1 if trial % 8 else -1)
    elif trial % 4 == 1: # special: b in span{1,u}
        b = np.cos(t) * basis(8, 0) + np.sin(t) * u
    else:                # generic b in H(u,n)
        q = unit(rng.standard_normal(4)); b = q[0] * basis(8, 0) + q[1] * u + q[2] * n + q[3] * mulO(u, n)
    x = pair(u, b) / np.sqrt(2); y = pair(mulO(n, u), mulO(b, n)) / np.sqrt(2)
    assert np.allclose(mul('Sm', x, y), 0, atol=1e-9)
    ranks.add(rank(np.hstack([R('Sm', y), L('Sm', x)])))
print('  ranks found:', ranks)

# ---------------------------------------------------------------- octave swap
print('=== the 15 basis hyperplanes of F_2^4: which are composition (octonion) subalgebras? ===')
def hyperplanes():
    # nonzero linear functionals on F_2^4 ; hyperplane = kernel
    for f in range(1, 16):
        yield f, [g for g in range(16) if bin(f & g).count('1') % 2 == 0]
def is_composition(name, H):
    idx = np.array(H)
    for _ in range(20):
        x = np.zeros(16); y = np.zeros(16)
        x[idx] = rng.standard_normal(8); y[idx] = rng.standard_normal(8)
        z = mul(name, x, y)
        if not np.allclose(z[[i for i in range(16) if i not in H]], 0): return 'not closed'
        if abs(norm2(z) - norm2(x) * norm2(y)) > 1e-8: return False
    return True
tab = []
for f, H in hyperplanes():
    kind = 'V (founding octave)' if f == 8 else ('contains l' if 8 in H else 'avoids l')
    tab.append((f, H, kind, is_composition('S', H), is_composition('Sm', H)))
for f, H, kind, s, m in tab:
    print(f'  f={f:2d} H={H} [{kind:20s}]  S: {s}   Sm: {m}')
ok('S: octaves = V + the 7 hyperplanes through l', all((s == (kind != 'avoids l')) for f, H, kind, s, m in tab))
ok('Sm: octaves = the 8 hyperplanes avoiding l', all((m == (kind != 'contains l')) for f, H, kind, s, m in tab))

