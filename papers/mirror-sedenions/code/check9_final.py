# subalgebra generated by a dead pair
def generated_dim(name, gens):
    B = np.array(gens, dtype=float)
    while True:
        # orthonormalize
        Uu, s, Vt = np.linalg.svd(B); r = int(np.sum(s > 1e-9)); B = Vt[:r]
        new = [mul(name, B[i], B[j]) for i in range(r) for j in range(r)]
        B2 = np.vstack([B] + new); Uu, s, Vt = np.linalg.svd(B2); r2 = int(np.sum(s > 1e-9))
        if r2 == r: return r, Vt[:r]
        B = Vt[:r2]
for name in ['S', 'Sm']:
    u = rand_im8(); n = rand_im8(); n = unit(n - (n @ u) * u)
    if name == 'S':
        x = pair(u, n)
    else:
        q = unit(rng.standard_normal(4)); b = q[0] * basis(8, 0) + q[1] * u + q[2] * n + q[3] * mulO(u, n); x = pair(u, b)
    K = L(name, x); U, s, Vt = np.linalg.svd(K); ker = Vt[-nullity(K):]; y = ker[0]
    r, B = generated_dim(name, [basis(16, 0), x, y])
    comp = all(abs(norm2(mul(name, B.T @ rng.standard_normal(r), B.T @ rng.standard_normal(r))) - 1) < 1e-8 or True for _ in range(1))
    # composition test
    cz = True
    for _ in range(10):
        p = B.T @ rng.standard_normal(r); q_ = B.T @ rng.standard_normal(r)
        cz &= abs(norm2(mul(name, p, q_)) - norm2(p) * norm2(q_)) < 1e-8
    print(f'  {name}: subalgebra generated by a dead pair (x, y) has dimension {r}; composition (octonion)? {cz}')

