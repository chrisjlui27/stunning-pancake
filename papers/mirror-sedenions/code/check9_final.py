import numpy as np
from cd import *
rng = np.random.default_rng(9)
def ok(label, cond): print(('PASS ' if cond else 'FAIL ') + label)
def rand_im8():
    v = rng.standard_normal(8); v[0] = 0; return unit(v)
def pair(a, b): return np.concatenate([a, b])

# quaternion subalgebra Q = H(e1,e2) = span{1,e1,e2,e3} ; complement Q eps with eps = e4
Q = [0, 1, 2, 3]; Qe = [4, 5, 6, 7]
def toQ(v):   # v in R^4 -> octonion in Q
    o = np.zeros(8); o[Q] = v; return o
def q_of(o): return o[Q]
def toQe(v):  # v in R^4 -> octonion v eps in Q eps  (as (0,v) in CD(Q))
    o = np.zeros(8); o[Qe] = v; return o
def mulQ(p, q): return q_of(mulO(toQ(p), toQ(q)))
def cq(v): w = -v.copy(); w[0] = v[0]; return w

a = rng.standard_normal(4); b = rng.standard_normal(4)
x = pair(toQ(a), toQ(b)); N = norm2(x)
A = np.column_stack([assoc('Sm', x, x, basis(16, i)) for i in range(16)])   # alt_x matrix
# block on M(Q): y = (c, d) with c,d in Q :  alt_x(c,d) = ([dbar b, a], b [cbar, abar])
good = True
for _ in range(10):
    c = rng.standard_normal(4); d = rng.standard_normal(4)
    y = pair(toQ(c), toQ(d)); z = A @ y
    db = mulQ(cq(d), b)
    pred1 = mulQ(db, a) - mulQ(a, db)
    pred2 = mulQ(b, mulQ(cq(c), cq(a)) - mulQ(cq(a), cq(c)))
    good &= np.allclose(z, pair(toQ(pred1), toQ(pred2)))
ok('alt_x on M(Q): alt_x(c,d) = ([d* b, a], b[c*, a*])', good)
# block on complement: alt_x(c eps, d eps) = ((d wbar) eps, (c w) eps),  w = abar b - b a
w = mulQ(cq(a), b) - mulQ(b, a)
good = True
for _ in range(10):
    c = rng.standard_normal(4); d = rng.standard_normal(4)
    y = pair(toQe(c), toQe(d)); z = A @ y
    good &= np.allclose(z, pair(toQe(mulQ(d, cq(w))), toQe(mulQ(c, w))))
ok('alt_x on M(Q)^perp: alt_x(c eps, d eps) = ((d w*) eps, (c w) eps), w = a* b - b a', good)
# w = 2(<a,b> - b0 a)
ok('w = 2(<a,b> - b0 a)', np.allclose(w, 2 * ((a @ b) * np.eye(4)[0] - b[0] * a)))
# blocks invariant
ok('L_x preserves the splitting M(Q) + M(Q)^perp', np.allclose(L('Sm', x)[np.ix_([i for i in range(16) if i % 8 >= 4], [i for i in range(16) if i % 8 < 4])], 0) and np.allclose(L('Sm', x)[np.ix_([i for i in range(16) if i % 8 < 4], [i for i in range(16) if i % 8 >= 4])], 0))
# kernel of alt_x = C_a + (b C_a) l  for generic x
a8 = toQ(a); b8 = toQ(b); ima = a8.copy(); ima[0] = 0
Ca = np.column_stack([basis(8, 0), unit(ima)])
K = np.column_stack([pair(Ca[:, 0], np.zeros(8)), pair(Ca[:, 1], np.zeros(8)), pair(np.zeros(8), mulO(b8, Ca[:, 0])), pair(np.zeros(8), mulO(b8, Ca[:, 1]))])
ok('ker alt_x = C_a + (b C_a) l  (4-dim, generic x)', nullity(A) == 4 and np.allclose(A @ K, 0, atol=1e-9))
# it is a quaternion subalgebra (composition)
comp = True
for _ in range(10):
    u_ = K @ rng.standard_normal(4); v_ = K @ rng.standard_normal(4); z = mul('Sm', u_, v_)
    comp &= np.allclose(K @ np.linalg.lstsq(K, z, rcond=None)[0], z) and abs(norm2(z) - norm2(u_) * norm2(v_)) < 1e-8
ok('the chart C_a + (b C_a) l is a composition subalgebra (= H)', comp)

# alternative elements of Sm : alt_x = 0 iff x in O or x in R + O l
def is_alt(name, x):
    A = np.column_stack([assoc(name, x, x, basis(16, i)) for i in range(16)]); return np.allclose(A, 0, atol=1e-9)
ok('Sm: l is alternative; S: l is not', is_alt('Sm', basis(16, 8)) and not is_alt('S', basis(16, 8)))
ok('Sm: (a0, b) alternative for any b', all(is_alt('Sm', pair(rng.random() * basis(8, 0), rand(8, rng))) for _ in range(5)))
ok('Sm: (a, b) with Im a != 0 and b != 0 is not alternative', not any(is_alt('Sm', pair(rand(8, rng), rand(8, rng))) for _ in range(5)))
# S: (a, b) with b in span{1, Im a} is alternative (the Dray charts)
u = rand_im8(); ok('S: (a, b) with b in span{1, Im a} is alternative', all(is_alt('S', pair(rng.random() * basis(8, 0) + rng.random() * u, rng.random() * basis(8, 0) + rng.random() * u)) for _ in range(5)))

