print('  uniform P1^T tower: dimension-8 stage is a composition algebra?', comp8)
def der_dim(name):
    T = struct(name); n = T.shape[0]; rows = []
    for i in range(n):
        for j in range(n):
            eq = np.zeros((n, n, n))
            for m in range(n): eq[:, :, m][np.arange(n), np.arange(n)] += T[i, j, m]
            for p in range(n): eq[:, p, i] -= T[p, j, :]; eq[:, p, j] -= T[i, p, :]
            rows.append(eq.reshape(n, n * n))
    return nullity(np.vstack(rows))
print('  uniform P1^T tower: Der dims at 8 and 16:', der_dim('U8'), der_dim('U16'), ' (S\' has 14)')
